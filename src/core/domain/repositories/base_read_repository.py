from abc import ABC, abstractmethod

from core.domain.specifications import Specification


class IReadRepository[TAggregate, TId](ABC):
    """Global port for read-only operations (Query side in CQRS).

    Implemented by infrastructure adapters (e.g., SQLAlchemy read repositories,
    in-memory query stores). A read repository:
    - deals strictly with read models / DTOs optimized for queries and views;
    - performs zero mutations or domain event dispatches;
    - handles retrieval, existence checks, and specification-based searches with pagination.
    """

    @abstractmethod
    async def get_by_id(self, aggregate_id: TId) -> TAggregate | None:
        """Load a single read model by its identifier.

        Returns None if no matching record is found.
        """
        ...

    @abstractmethod
    async def exists(self, aggregate_id: TId) -> bool:
        """Check whether a read model with the given identifier exists."""
        ...

    @abstractmethod
    async def find(
        self,
        spec: Specification[TAggregate],
        *,
        limit: int = 50,
        offset: int = 0,
    ) -> list[TAggregate]:
        """Search for read models matching the given specification, supporting pagination."""
        ...

    @abstractmethod
    async def save(self, aggregate: TAggregate) -> None:
        """Persist new domain events generated by the aggregate."""
        ...